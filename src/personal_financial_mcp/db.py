def query_transactions(
    conn: Connection,
    start: date,
    end: date,
    account_ids: list[str] | None = None,
    search: str | None = None,
    include_pending: bool = True,
    limit: int = 500,
    exclude_internal: bool = False,
    category_id: int | None = None,
    uncategorized: bool = False,
) -> list[dict[str, Any]]:
    sql = """
        SELECT t.date, t.amount, t.description, t.payee, t.payee_normalized, t.memo, t.pending,
               a.name AS account, t.account_id, t.id, t.is_internal_transfer, t.transfer_pair_id,
               c.name AS category, t.category_source
        FROM transactions t JOIN accounts a ON a.id = t.account_id LEFT JOIN categories c ON c.id = t.category_id
        WHERE t.date BETWEEN %s AND %s
    """
    params: list[Any] = [start, end]
    if account_ids:
        sql += " AND t.account_id = ANY(%s)"
        params.append(account_ids)
    if search:
        sql += " AND (t.description ILIKE %s OR t.payee ILIKE %s OR t.memo ILIKE %s OR t.payee_normalized ILIKE %s)"
        params += [f"%{search}%"] * 4
    if not include_pending:
        sql += " AND NOT t.pending"
    if exclude_internal:
        sql += " AND NOT t.is_internal_transfer"
    if category_id is not None:
        sql += " AND t.category_id = %s"
        params.append(category_id)
    if uncategorized:
        sql += " AND t.category_id IS NULL"
    sql += " ORDER BY t.date DESC LIMIT %s"
    params.append(limit)
    return [dict(r) | {"amount": round(r["amount"], 2)} for r in conn.execute(sql, params)]
