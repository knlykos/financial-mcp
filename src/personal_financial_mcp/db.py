# Connection string: DATABASE_URL, else this file. Both stay out of git.
DATABASE_URL_FILE = PROJECT_ROOT / ".database-url"
# Personal aliases/rules (employer, own name...) that must stay out of git.
LOCAL_RULES_FILE = PROJECT_ROOT / "local_rules.json"


def database_url() -> str:
    url = os.environ.get("DATABASE_URL", "").strip()
    if not url and DATABASE_URL_FILE.exists():
        url = DATABASE_URL_FILE.read_text().strip()
    if not url:
        raise ToolError(f"No database configured: set DATABASE_URL or put the Postgres URL in {DATABASE_URL_FILE}.")
    return url


# --- Migrations ---------------------------------------------------------------------------------
# Each migration runs once, in order; schema_version stores how many have been applied. Postgres DDL is
# transactional, so a failed upgrade rolls back entirely (and Neon keeps point-in-time history besides).


def _m1_base(conn: Connection) -> None:
    conn.execute(
        """
        CREATE TABLE accounts (
            id                text PRIMARY KEY,
            name              text NOT NULL,
            institution       text,
            currency          text,
            balance           double precision,
            available_balance double precision,
            balance_date      date,
            synced_at         timestamp,
            kind              text NOT NULL DEFAULT 'depository' CHECK (kind IN ('depository', 'credit'))
        );

        CREATE TABLE categories (
            id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name   text NOT NULL UNIQUE,
            parent text,
            kind   text NOT NULL CHECK (kind IN ('income', 'expense', 'transfer', 'debt')),
            source text NOT NULL DEFAULT 'user'  -- seed | local | user
        );

        CREATE TABLE transactions (
            account_id           text NOT NULL REFERENCES accounts(id),
            id                   text NOT NULL,
            date                 date NOT NULL,  -- transacted_at, else posted, else sync day (local date)
            posted               date,
            amount               double precision NOT NULL,  -- negative = money out, positive = money in
            description          text,
            payee                text,
            memo                 text,
            pending              boolean NOT NULL DEFAULT false,
            payee_normalized     text NOT NULL DEFAULT '',
            is_internal_transfer boolean NOT NULL DEFAULT false,
            transfer_pair_id     text,
            category_id          integer REFERENCES categories(id),
            category_source      text NOT NULL DEFAULT 'none',  -- rule | manual | none
            PRIMARY KEY (account_id, id)
        );
        CREATE INDEX idx_transactions_date ON transactions(date);
        CREATE INDEX idx_transactions_payee_normalized ON transactions(payee_normalized);
        CREATE INDEX idx_transactions_pair ON transactions(transfer_pair_id);
        CREATE INDEX idx_transactions_category ON transactions(category_id);

        CREATE TABLE payee_aliases (
            id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            pattern    text NOT NULL UNIQUE,  -- case-insensitive regex
            normalized text NOT NULL,
            field      text NOT NULL DEFAULT 'payee',  -- payee (description if no payee) | description
            priority   integer NOT NULL DEFAULT 100,  -- lower wins
            source     text NOT NULL DEFAULT 'user'   -- seed | local | user
        );

        CREATE TABLE category_rules (
            id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            match_field text NOT NULL,  -- payee_normalized | payee | description | memo
            match_type  text NOT NULL CHECK (match_type IN ('exact', 'contains', 'regex')),
            pattern     text NOT NULL,
            category_id integer NOT NULL REFERENCES categories(id),
            direction   text NOT NULL DEFAULT 'any' CHECK (direction IN ('any', 'in', 'out')),
            priority    integer NOT NULL DEFAULT 10,  -- lower wins
            source      text NOT NULL DEFAULT 'user',  -- seed | local | user
            created_at  timestamp NOT NULL
        );
        """
    )
    # Seeding, normalization, transfer matching and categorization happen in _refresh_derived.


_DEPOSITORY_WORDS = re.compile(r"\b(CHECKING|SAVINGS|MONEY MARKET)\b", re.I)
_CREDIT_WORDS = re.compile(r"\b(CARD|CREDIT|QUICKSILVER|PLATINUM|SAVOR|VENTURE|VISA|MASTERCARD|AMEX)\b", re.I)


def infer_account_kind(name: str | None, institution: str | None, balance: float | None) -> str:
    """'credit' for credit cards, else 'depository'. SimpleFIN doesn't report the account type, so guess it."""
    text = f"{name or ''} {institution or ''}"
    if _DEPOSITORY_WORDS.search(text):
        return "depository"
    if _CREDIT_WORDS.search(text):
        return "credit"
    return "credit" if (balance or 0) < 0 else "depository"


def _m2_oauth(conn: Connection) -> None:
    """Clients and tokens of the remote server's OAuth (auth.py). Tokens are stored as SHA-256 hashes."""
    conn.execute(
        """
        CREATE TABLE oauth_clients (
            client_id  text PRIMARY KEY,
            info       text NOT NULL,  -- OAuthClientInformationFull as JSON
            created_at timestamp NOT NULL DEFAULT now()
        );

        CREATE TABLE oauth_tokens (
            token_hash text PRIMARY KEY,
            kind       text NOT NULL CHECK (kind IN ('access', 'refresh')),
            client_id  text NOT NULL,
            scopes     text NOT NULL,
            resource   text,
            expires_at bigint NOT NULL  -- unix seconds
        );
        """
    )


def _m3_rule_per_transaction(conn: Connection) -> None:
    """Which rule categorized each transaction, so rules can report their own match count."""
    conn.execute(
        """
        ALTER TABLE transactions
            ADD COLUMN category_rule_id integer REFERENCES category_rules(id) ON DELETE SET NULL;
        CREATE INDEX idx_transactions_rule ON transactions(category_rule_id);
        """
    )
    # Filled by the recategorize in _refresh_derived.


MIGRATIONS: list[Callable[[Connection], None]] = [_m1_base, _m2_oauth, _m3_rule_per_transaction]

# Serializes migrations when several server processes (Claude Code, Claude Desktop) start at once.
_MIGRATION_LOCK = 0x70666D  # "pfm"


def schema_version(conn: Connection) -> int:
    row = conn.execute("SELECT version FROM schema_version").fetchone()
    return row[0] if row else 0


def _migrate(conn: Connection) -> None:
    conn.execute("SELECT pg_advisory_xact_lock(%s)", (_MIGRATION_LOCK,))
    conn.execute("CREATE TABLE IF NOT EXISTS schema_version (version integer NOT NULL)")
    version = schema_version(conn)
    if version >= len(MIGRATIONS):
        return
    for migration in MIGRATIONS[version:]:
        migration(conn)
    conn.execute("DELETE FROM schema_version")
    conn.execute("INSERT INTO schema_version (version) VALUES (%s)", (len(MIGRATIONS),))


# --- Aliases --------------------------------------------------------------------------------------


def _load_local_rules() -> dict[str, Any]:
    if not LOCAL_RULES_FILE.exists():
        return {}
    return json.loads(LOCAL_RULES_FILE.read_text(encoding="utf-8"))


def _sync_aliases(conn: Connection) -> None:
    """Make the seed and local aliases in the DB match the code and local_rules.json; renormalize if they changed."""
    wanted = [(p, n, "description", 90, "seed") for p, n in SEED_DESCRIPTION_ALIASES]
    wanted += [(p, n, "payee", 100, "seed") for p, n in SEED_ALIASES]
    wanted += [
        (a["pattern"], a["normalized"], a.get("field", "payee"), 50, "local")
        for a in _load_local_rules().get("payee_aliases", [])
    ]

    snapshot = lambda: conn.execute(
        "SELECT pattern, normalized, field, priority, source FROM payee_aliases ORDER BY id"
    ).fetchall()
    before = [tuple(r) for r in snapshot()]
    conn.execute(
        "DELETE FROM payee_aliases WHERE source IN ('seed', 'local') AND pattern <> ALL(%s)", ([w[0] for w in wanted],)
    )
    executemany(
        conn,
        """
        INSERT INTO payee_aliases (pattern, normalized, field, priority, source) VALUES (%s, %s, %s, %s, %s)
        ON CONFLICT (pattern) DO UPDATE SET normalized = excluded.normalized, field = excluded.field,
                                            priority = excluded.priority, source = excluded.source
        """,
        wanted,
    )
    stale = conn.execute("SELECT 1 FROM transactions WHERE payee_normalized = '' LIMIT 1").fetchone()
    if [tuple(r) for r in snapshot()] != before or stale:
        renormalize_all(conn)


def load_aliases(conn: Connection) -> list[Alias]:
    rows = conn.execute("SELECT pattern, normalized, field FROM payee_aliases ORDER BY priority, id").fetchall()
    return compile_aliases([(r["pattern"], r["normalized"], r["field"]) for r in rows])


def renormalize_all(conn: Connection) -> int:
    aliases = load_aliases(conn)
    rows = conn.execute("SELECT account_id, id, payee, description, payee_normalized FROM transactions").fetchall()
    updates = [
        (new, r["account_id"], r["id"])
        for r in rows
        if (new := normalize_payee(r["payee"], r["description"], aliases)) != r["payee_normalized"]
    ]
    executemany(conn, "UPDATE transactions SET payee_normalized = %s WHERE account_id = %s AND id = %s", updates)
    return len(rows)


def _refresh_derived(conn: Connection) -> None:
    """Recompute everything derived from raw transactions, once per process.

    Cheap at personal-finance scale, and it repairs rows written by an older version of the server.
    """
    _sync_aliases(conn)
    match_internal_transfers(conn)
    categories.sync_seed_rules(conn, _load_local_rules())
    categories.recategorize(conn)


# --- Connection -----------------------------------------------------------------------------------

_initialized: set[str] = set()


@contextmanager
def connect() -> Iterator[Connection]:
    """Open the DB (migrating it on first use in this process), commit on success, always close."""
    url = database_url()
    with pg.connect(url) as conn:
        if url not in _initialized:
            _migrate(conn)
            _refresh_derived(conn)
            conn.commit()
            _initialized.add(url)
        yield conn


# --- Writes ---------------------------------------------------------------------------------------


def _local_date(ts: int | None) -> str | None:
    return datetime.fromtimestamp(ts).date().isoformat() if ts else None


def _num(value: str | None) -> float | None:
    return float(value) if value not in (None, "") else None


def upsert_accounts(conn: Connection, accounts: list[dict[str, Any]]) -> None:
    """Insert or refresh accounts. `kind` is guessed only on insert, so a manual correction in the DB sticks."""
    now = datetime.now().isoformat(timespec="seconds")
    executemany(
        conn,
        """
        INSERT INTO accounts (id, name, institution, currency, balance, available_balance, balance_date, synced_at,
                              kind)
        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)
        ON CONFLICT (id) DO UPDATE SET
            name = excluded.name, institution = excluded.institution, currency = excluded.currency,
            balance = excluded.balance, available_balance = excluded.available_balance,
            balance_date = excluded.balance_date, synced_at = excluded.synced_at
        """,
        [
            (
                a["id"],
                a["name"],
                a["org"].get("name") or a["org"].get("domain"),
                a.get("currency"),
                _num(a.get("balance")),
                _num(a.get("available-balance")),
                _local_date(a.get("balance-date")),
                now,
                infer_account_kind(a["name"], a["org"].get("name"), _num(a.get("balance"))),
            )
            for a in accounts
        ],
    )
    # Some card issuers (Capital One) report 0 available credit when they don't share it; a real 0 can't be
    # told apart, so store "unknown" rather than claim the card is maxed out.
    conn.execute("UPDATE accounts SET available_balance = NULL WHERE kind = 'credit' AND available_balance = 0")


def fix_balance_signs(conn: Connection) -> list[str]:
    """Restore the minus sign SimpleFIN drops on negative checking balances (overdrawn -64.32 arrives as "64.32").

    The bank's available balance is the posted balance plus pending transactions, so keep the sign combination
    for which that holds. Balances are left alone when the reported signs already fit, or when no single
    alternative does (holds, stale pending rows). Returns the ids of the accounts that were corrected.
    """
    rows = conn.execute(
        """
        SELECT a.id, a.balance, a.available_balance,
               COALESCE(SUM(t.amount) FILTER (WHERE t.pending), 0) AS pending
        FROM accounts a LEFT JOIN transactions t ON t.account_id = a.id
        WHERE a.kind = 'depository' AND a.balance IS NOT NULL AND a.available_balance IS NOT NULL
        GROUP BY a.id
        """
    ).fetchall()
    fixed = []
    for r in rows:
        bal, avail, pending = abs(r["balance"]), abs(r["available_balance"]), r["pending"]
        fits = {
            (sb * bal, sa * avail)
            for sb in (1, -1)
            for sa in (1, -1)
            if round(sa * avail - (sb * bal + pending), 2) == 0
        }
        if (r["balance"], r["available_balance"]) in fits or len(fits) != 1:
            continue
        balance, available = fits.pop()
        conn.execute(
            "UPDATE accounts SET balance = %s, available_balance = %s WHERE id = %s", (balance, available, r["id"])
        )
        fixed.append(r["id"])
    return fixed


def upsert_transactions(conn: Connection, accounts: list[dict[str, Any]]) -> int:
    """Store transactions; returns how many rows were written."""
    aliases = load_aliases(conn)
    # Pending transactions often change id once they post, so drop old pending rows and take the fresh set.
    conn.execute("DELETE FROM transactions WHERE account_id = ANY(%s) AND pending", ([a["id"] for a in accounts],))
    return executemany(
        conn,
        """
        INSERT INTO transactions (account_id, id, date, posted, amount, description, payee, memo, pending,
                                  payee_normalized)
        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
        ON CONFLICT (account_id, id) DO UPDATE SET
            date = excluded.date, posted = excluded.posted, amount = excluded.amount,
            description = excluded.description, payee = excluded.payee, memo = excluded.memo,
            pending = excluded.pending, payee_normalized = excluded.payee_normalized
        """,
        [
            (
                a["id"],
                t["id"],
                # Pending transactions may have posted = 0 and no transacted_at; treat them as today.
                _local_date(t.get("transacted_at") or t.get("posted")) or date.today().isoformat(),
                _local_date(t.get("posted")),
                float(t["amount"]),
                t.get("description"),
                t.get("payee"),
                t.get("memo") or None,
                bool(t.get("pending")),
                normalize_payee(t.get("payee"), t.get("description"), aliases),
            )
            for a in accounts
            for t in a.get("transactions", [])
        ],
    )


